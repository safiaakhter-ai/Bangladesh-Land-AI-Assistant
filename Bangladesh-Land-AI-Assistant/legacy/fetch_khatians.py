class TokenExpiredError(Exception):
    """Raised when HTTP 401 Unauthorized is returned by DLRMS API and auto-refresh fails."""
    pass

def obtain_fresh_bearer_token(target_url="https://dlrms.land.gov.bd/"):
    """
    Launch headless Chrome via Selenium with performance logging to intercept
    the dynamic Bearer token automatically generated by the DLRMS client app.
    """
    try:
        from selenium import webdriver
        from selenium.webdriver.chrome.options import Options

        print("\n  [Auto-Token] Launching headless browser to obtain fresh Bearer token...")
        chrome_options = Options()
        chrome_options.add_argument('--headless=new')
        chrome_options.add_argument('--disable-gpu')
        chrome_options.add_argument('--no-sandbox')
        chrome_options.add_argument('--disable-dev-shm-usage')
        chrome_options.set_capability('goog:loggingPrefs', {'performance': 'ALL'})

        driver = webdriver.Chrome(options=chrome_options)
        try:
            driver.get(target_url)
            time.sleep(4)  # Allow frontend JS bundle to execute and issue API requests
            logs = driver.get_log('performance')
            for entry in logs:
                try:
                    log_msg = json.loads(entry['message'])['message']
                    if log_msg.get('method') == 'Network.requestWillBeSent':
                        headers = log_msg['params']['request'].get('headers', {})
                        for header_name, header_val in headers.items():
                            if header_name.lower() == 'authorization' and str(header_val).startswith('Bearer '):
                                token = str(header_val).split('Bearer ', 1)[1].strip()
                                if token and len(token) > 10:
                                    print(f"  [Auto-Token] Successfully obtained fresh token: {token[:12]}...")
                                    return token
                except Exception:
                    pass
        finally:
            driver.quit()
    except Exception as e:
        print(f"  [Auto-Token Error] Failed to retrieve fresh token via Selenium: {e}")
    return None

class DLRMSKhatianFetcher:
    def __init__(self, db_path, bearer_token=None, delay=0.05, default_survey="CS", page_size=100, timeout=30, max_retries=8, workers=10, auto_refresh_token=True):
        self.db_path = db_path
        self.delay = delay
        self.default_survey = default_survey
        self.page_size = page_size
        self.bearer_token = bearer_token or DEFAULT_BEARER_TOKEN
        self.timeout = timeout
        self.max_retries = max_retries
        self.workers = workers
        self.auto_refresh_token = auto_refresh_token
        self.token_lock = threading.Lock()
        self.thread_local = threading.local()
        self.stop_event = threading.Event()
        self.throttle_until = 0.0
        
        self._init_session()
        self._init_db()

    def _init_session(self):
        """Create default requests Session for single-threaded setup steps."""
        self.session = requests.Session()
        adapter = HTTPAdapter(pool_connections=self.workers * 2, pool_maxsize=self.workers * 2)
        self.session.mount("https://", adapter)
        self.session.mount("http://", adapter)
        self.session.headers.update({
            "User-Agent": DEFAULT_USER_AGENT,
            "Accept": "application/json",
            "Accept-Language": "en-US,en;q=0.9",
            "Referer": "https://dlrms.land.gov.bd/",
            "Origin": "https://dlrms.land.gov.bd",
            "Authorization": f"Bearer {self.bearer_token}",
            "Connection": "keep-alive"
        })

    def get_thread_session(self):
        """Get or create a thread-local requests Session instance to prevent lock contention between worker threads."""
        if not hasattr(self.thread_local, "session"):
            sess = requests.Session()
            adapter = HTTPAdapter(pool_connections=10, pool_maxsize=10)
            sess.mount("https://", adapter)
            sess.mount("http://", adapter)
            sess.headers.update({
                "User-Agent": DEFAULT_USER_AGENT,
                "Accept": "application/json",
                "Accept-Language": "en-US,en;q=0.9",
                "Referer": "https://dlrms.land.gov.bd/",
                "Origin": "https://dlrms.land.gov.bd",
                "Authorization": f"Bearer {self.bearer_token}",
                "Connection": "keep-alive"
            })
            self.thread_local.session = sess
        else:
            self.thread_local.session.headers["Authorization"] = f"Bearer {self.bearer_token}"
        return self.thread_local.session

    def _get_connection(self):
        """Get SQLite connection configured for concurrent multi-threaded writes."""
        conn = sqlite3.connect(self.db_path, timeout=60.0)
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA synchronous=NORMAL;")
        return conn

    def _init_db(self):
        """Initialize SQLite tables to maintain persistent state and minimize memory overhead."""
        with self._get_connection() as conn:
            cursor = conn.cursor()
            
            # Progress tracker for mouza JL_NUMBER_IDs
            cursor.execute('''
                CREATE TABLE IF NOT EXISTS mouza_progress (
                    jl_number_id INTEGER PRIMARY KEY,
                    survey_name TEXT,
                    status TEXT DEFAULT 'pending',
                    total_items INTEGER DEFAULT 0,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            ''')
            
            # Index table storing discovered khatian IDs per mouza
            cursor.execute('''
                CREATE TABLE IF NOT EXISTS khatian_index (
                    khatian_id INTEGER PRIMARY KEY,
                    jl_number_id INTEGER,
                    survey_name TEXT,
                    khatian_no TEXT,
                    fetched_detail INTEGER DEFAULT 0,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            ''')
            
            # Full khatian detail data
            cursor.execute('''
                CREATE TABLE IF NOT EXISTS khatian_details (
                    khatian_id INTEGER PRIMARY KEY,
                    jl_number_id INTEGER,
                    survey_name TEXT,
                    detail_json TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            ''')
            
            conn.commit()

    def refresh_bearer_token_if_needed(self, failed_token):
        """Thread-safe handler to retrieve a fresh token if failed_token matches current bearer_token."""
        with self.token_lock:
            if self.bearer_token == failed_token:
                new_token = obtain_fresh_bearer_token()
                if new_token:
                    self.bearer_token = new_token
                    self.session.headers["Authorization"] = f"Bearer {self.bearer_token}"
                    return True
                return False
            else:
                # Token was already refreshed by another worker thread!
                return True

    def make_request_with_retry(self, url, params=None):
        """Execute HTTP GET request with retries, adaptive throttling, randomized backoff jitter, and 401 token auto-refresh."""
        attempt = 0
        while attempt < self.max_retries:
            if self.stop_event.is_set():
                return None
                
            # Check global adaptive throttle
            now = time.time()
            if now < self.throttle_until:
                import random
                sleep_for = (self.throttle_until - now) + random.uniform(0.1, 0.4)
                time.sleep(sleep_for)

            current_token = self.bearer_token
            session = self.get_thread_session()
            try:
                resp = session.get(url, params=params, timeout=self.timeout)
                if resp.status_code == 200:
                    if self.delay > 0:
                        time.sleep(self.delay)
                    return resp.json()
                elif resp.status_code in (429, 500, 502, 503, 504):
                    import random
                    with self.token_lock:
                        # Set adaptive throttle for all threads to slow down
                        self.throttle_until = max(self.throttle_until, time.time() + 2.0)

                    base_wait = min((1.5 ** attempt) + 1.5, 12)
                    jitter = random.uniform(0.2, 1.0)
                    wait_time = base_wait + jitter
                    
                    if attempt >= 2 or resp.status_code != 429:
                        print(f"\n  [Rate Limit 429] Server throttling. Retrying in {wait_time:.1f}s (Attempt {attempt + 1}/{self.max_retries})...")
                    
                    time.sleep(wait_time)
                elif resp.status_code == 401:
                    print(f"\n  [Error 401] Bearer token expired or invalid for {url}.")
                    if self.auto_refresh_token:
                        if self.refresh_bearer_token_if_needed(current_token):
                            print("  [Auto-Token] Resuming request with refreshed Bearer token...")
                            attempt += 1
                            continue
                    raise TokenExpiredError(f"HTTP 401 Unauthorized for {url}")
                else:
                    print(f"\n  [Error {resp.status_code}] {url}: {resp.text[:200]}")
                    return None
            except requests.exceptions.RequestException as e:
                if attempt >= 2:
                    self._init_session()
                wait_time = min((2 ** attempt) + 1, 30)
                print(f"\n  [Error] Network exception: {e}. Retrying in {wait_time}s (Attempt {attempt + 1}/{self.max_retries})...")
                time.sleep(wait_time)
            attempt += 1
        return None

    def fetch_index_for_mouza(self, jl_number_id, survey_name="CS"):
        """Fetch all index khatian summary items for a single Mouza record."""
        page_no = 1
        total_discovered = 0
        survey_code = (survey_name or self.default_survey).strip().upper()
        success_all_pages = True
        
        while True:
            if self.stop_event.is_set():
                break
                
            url = f"{DEFAULT_BASE_URL}/{survey_code}"
            params = {
                "SURVEY": survey_code,
                "JL_NUMBER_ID": jl_number_id,
                "PAGE_NO": page_no,
                "PAGE_SIZE": self.page_size
            }
            
            response = self.make_request_with_retry(url, params=params)
            if not response or not response.get("success"):
                success_all_pages = False
                break
                
            data = response.get("data", {})
            items = data.get("items", []) if isinstance(data, dict) else []
            
            if not items:
                break
                
            with self._get_connection() as conn:
                cursor = conn.cursor()
                for item in items:
                    khatian_id = item.get("ID")
                    khatian_no = str(item.get("KHATIAN_NO", ""))
                    if khatian_id:
                        cursor.execute('''
                            INSERT OR IGNORE INTO khatian_index (khatian_id, jl_number_id, survey_name, khatian_no)
                            VALUES (?, ?, ?, ?)
                        ''', (khatian_id, jl_number_id, survey_code, khatian_no))
                conn.commit()
                
            total_discovered += len(items)
            
            if len(items) < self.page_size:
                break
                
            page_no += 1

        final_status = 'completed' if success_all_pages else 'failed'
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute('''
                INSERT OR REPLACE INTO mouza_progress (jl_number_id, survey_name, status, total_items, updated_at)
                VALUES (?, ?, ?, ?, CURRENT_TIMESTAMP)
            ''', (jl_number_id, survey_code, final_status, total_discovered))
            conn.commit()
            
        return total_discovered, success_all_pages

    def fetch_details_pending(self, batch_size=2000):
        """Fetch individual khatian details with overall progress percentage and adaptive speed control."""
        with self._get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT COUNT(*) FROM khatian_index")
            total_index_count = cursor.fetchone()[0]
            cursor.execute("SELECT COUNT(*) FROM khatian_details")
            total_saved_count = cursor.fetchone()[0]

        print(f"\n--- STAGE 2: Fetching Full Khatian Detail Records ---")
        print(f"Overall Progress Starting Point: {total_saved_count:,} / {total_index_count:,} khatians saved ({total_saved_count / total_index_count * 100:.2f}%)\n")

        while not self.stop_event.is_set():
            with self._get_connection() as conn:
                cursor = conn.cursor()
                cursor.execute('''
                    CREATE INDEX IF NOT EXISTS idx_khatian_fetched ON khatian_index(fetched_detail);
                ''')
                cursor.execute('''
                    SELECT khatian_id, jl_number_id, survey_name FROM khatian_index 
                    WHERE fetched_detail = 0 
                    LIMIT ?
                ''', (batch_size,))
                rows = cursor.fetchall()
                
            if not rows:
                print("\n[Done] All khatian details have been fully fetched!")
                break
                
            print(f"Processing batch of {len(rows)} pending khatian details ({self.workers} Workers)...")
            
            def fetch_single_detail(row):
                if self.stop_event.is_set():
                    return (row[0], row[1], row[2], None)
                khatian_id, jl_number_id, survey_name = row
                survey_code = (survey_name or self.default_survey).strip().upper()
                detail_url = f"{DEFAULT_BASE_URL}/{survey_code}/{khatian_id}"
                
                resp_json = self.make_request_with_retry(detail_url)
                if resp_json and resp_json.get("success"):
                    detail_data = resp_json.get("data")
                    if detail_data:
                        raw_json_str = json.dumps(detail_data, ensure_ascii=False)
                        return (khatian_id, jl_number_id, survey_code, raw_json_str)
                return (khatian_id, jl_number_id, survey_code, None)

            success_items = []
            failed_ids = []
            start_time = time.time()
            
            with ThreadPoolExecutor(max_workers=self.workers) as executor:
                futures = {executor.submit(fetch_single_detail, row): row for row in rows}
                completed = 0
                for future in as_completed(futures):
                    if self.stop_event.is_set():
                        executor.shutdown(wait=False, cancel_futures=True)
                        break
                    res_khatian_id, res_jl_id, res_survey, detail_json = future.result()
                    completed += 1
                    if detail_json is not None:
                        success_items.append((res_khatian_id, res_jl_id, res_survey, detail_json))
                    else:
                        failed_ids.append(res_khatian_id)
                        
                    if completed % 100 == 0 or completed == len(rows):
                        elapsed = time.time() - start_time
                        speed = completed / elapsed if elapsed > 0 else 0
                        overall_collected = total_saved_count + len(success_items)
                        pct = (overall_collected / total_index_count * 100) if total_index_count > 0 else 0.0
                        print(f"  [Progress] Batch: {completed}/{len(rows)} | Collected: {overall_collected:,} / {total_index_count:,} ({pct:.2f}%) | Speed: {speed:.1f} rec/s")

            # Batch write to SQLite
            with self._get_connection() as conn:
                cursor = conn.cursor()
                if success_items:
                    cursor.executemany('''
                        INSERT OR REPLACE INTO khatian_details (khatian_id, jl_number_id, survey_name, detail_json)
                        VALUES (?, ?, ?, ?)
                    ''', success_items)
                    cursor.executemany('''
                        UPDATE khatian_index SET fetched_detail = 1 WHERE khatian_id = ?
                    ''', [(item[0],) for item in success_items])
                if failed_ids:
                    cursor.executemany('''
                        UPDATE khatian_index SET fetched_detail = -1 WHERE khatian_id = ?
                    ''', [(k_id,) for k_id in failed_ids])
                conn.commit()
            
            total_saved_count += len(success_items)
            elapsed_total = time.time() - start_time
            overall_speed = len(rows) / elapsed_total if elapsed_total > 0 else 0
            pct_now = (total_saved_count / total_index_count * 100) if total_index_count > 0 else 0.0
            print(f"  [Batch Saved] {len(success_items)} new records committed | Total DB Records: {total_saved_count:,} / {total_index_count:,} ({pct_now:.2f}%) [{overall_speed:.1f} rec/s]\n")

    def export_to_single_json(self, output_json_path):
        """Stream all stored khatian detail JSON objects from SQLite into a single JSON file without high RAM consumption."""
        print(f"\nExporting khatian details to single JSON file: {output_json_path}...")
        
        conn = sqlite3.connect(self.db_path)
        cursor = conn.cursor()
        
        cursor.execute("SELECT COUNT(*) FROM khatian_details")
        total_records = cursor.fetchone()[0]
        print(f"Found {total_records} records in database to export.")
        
        cursor.execute("SELECT detail_json FROM khatian_details")
        
        count = 0
        output_dir = os.path.dirname(output_json_path)
        if output_dir:
            os.makedirs(output_dir, exist_ok=True)

        with open(output_json_path, "w", encoding="utf-8") as f:
            f.write("[\n")
            first = True
            
            while True:
                rows = cursor.fetchmany(1000)
                if not rows:
                    break
                    
                for (raw_json,) in rows:
                    if not first:
                        f.write(",\n")
                    else:
                        first = False
                    
                    f.write("  " + raw_json)
                    count += 1
                    
                if count % 10000 == 0 and count > 0:
                    print(f"  Exported {count}/{total_records} records...")
                    
            f.write("\n]\n")
            
        conn.close()
        print(f"Successfully exported {count} records to '{output_json_path}'.")

def load_mouza_records_from_json(json_path, limit=None, override_survey=None):
    """Load Mouza IDs and SURVEY_NAME_EN from mouza JSON file."""
    if not os.path.exists(json_path):
        print(f"Error: File '{json_path}' not found!")
        sys.exit(1)

    print(f"Loading Mouza records from '{json_path}'...")
    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)
        
    mouzas = []
    if isinstance(data, dict):
        mouzas = data.get("data", [])
    elif isinstance(data, list):
        mouzas = data
        
    records = []
    for item in mouzas:
        if isinstance(item, dict) and "ID" in item:
            m_id = item["ID"]
            survey_name = override_survey or item.get("SURVEY_NAME_EN") or "CS"
            records.append((m_id, survey_name))
            
    if limit and limit > 0:
        records = records[:limit]
        
    print(f"Loaded {len(records)} total Mouza records.")
    return records

def main():
    parser = argparse.ArgumentParser(description="Automated High-Performance DLRMS Khatian Collector")
    parser.add_argument("--mouza-file", type=str, default=r"data/mouzas/all_mouzas.json", help="Path to mouza JSON file")
    parser.add_argument("--survey", type=str, default=None, help="Override survey name for all mouzas (e.g. CS, RS, BRS). If omitted, uses SURVEY_NAME_EN from each record.")
    parser.add_argument("--output-db", type=str, default="khatians.db", help="SQLite database path for state tracking")
    parser.add_argument("--output-json", type=str, default="all_khatians.json", help="Output single JSON file path")
    parser.add_argument("--bearer-token", type=str, default=DEFAULT_BEARER_TOKEN, help="Authorization Bearer token")
    parser.add_argument("--delay", type=float, default=0.05, help="Delay in seconds between HTTP requests (default: 0.05)")
    parser.add_argument("--timeout", type=int, default=30, help="HTTP request timeout in seconds (default: 30)")
    parser.add_argument("--max-retries", type=int, default=8, help="Max retry attempts for failed requests (default: 8)")
    parser.add_argument("--workers", type=int, default=10, help="Number of concurrent worker threads (default: 10)")
    parser.add_argument("--batch-size", type=int, default=2000, help="Batch size for DB querying & writing in Stage 2 (default: 2000)")
    parser.add_argument("--no-auto-token", action="store_true", help="Disable automatic Bearer token retrieval via headless Chrome on 401 error")
    parser.add_argument("--limit-mouzas", type=int, default=0, help="Limit number of Mouzas to process (0 = all)")
    parser.add_argument("--export-only", action="store_true", help="Export existing SQLite database to single JSON file without fetching")

    args = parser.parse_args()

    fetcher = DLRMSKhatianFetcher(
        db_path=args.output_db,
        bearer_token=args.bearer_token,
        delay=args.delay,
        default_survey=args.survey or "CS",
        timeout=args.timeout,
        max_retries=args.max_retries,
        workers=args.workers,
        auto_refresh_token=not args.no_auto_token
    )

    if args.export_only:
        fetcher.export_to_single_json(args.output_json)
        return

    # 1. Load Mouza Records
    mouza_records = load_mouza_records_from_json(args.mouza_file, limit=args.limit_mouzas if args.limit_mouzas > 0 else None, override_survey=args.survey)
    
    # 2. Check already completed Mouzas from DB
    conn = fetcher._get_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT jl_number_id FROM mouza_progress WHERE status = 'completed'")
    completed_mouzas = set(row[0] for row in cursor.fetchall())
    conn.close()
    
    pending_mouza_records = [rec for rec in mouza_records if rec[0] not in completed_mouzas]
    print(f"Found {len(completed_mouzas)} Mouzas already indexed. Pending Mouzas to process: {len(pending_mouza_records)}")
    
    try:
        # 3. Index Khatians for each Mouza (Concurrent execution)
        if pending_mouza_records:
            print(f"\n--- STAGE 1: Discovering Index Khatians per Mouza ({fetcher.workers} Workers) ---")
            completed_count = 0
            total_khatians_found = 0

            def process_mouza(rec):
                m_id, s_name = rec
                found_count, is_ok = fetcher.fetch_index_for_mouza(m_id, survey_name=s_name)
                return m_id, found_count, is_ok

            with ThreadPoolExecutor(max_workers=fetcher.workers) as executor:
                future_to_rec = {executor.submit(process_mouza, rec): rec for rec in pending_mouza_records}
                for future in as_completed(future_to_rec):
                    if fetcher.stop_event.is_set():
                        executor.shutdown(wait=False, cancel_futures=True)
                        break
                    m_id, found_count, is_ok = future.result()
                    completed_count += 1
                    total_khatians_found += found_count
                    if completed_count % 10 == 0 or completed_count == len(pending_mouza_records):
                        print(f"  Stage 1 Progress: {completed_count}/{len(pending_mouza_records)} Mouzas indexed ({total_khatians_found} total Khatians found)")
                
        # 4. Fetch Details for Discovered Khatians (Concurrent execution)
        fetcher.fetch_details_pending(batch_size=args.batch_size)

        # 5. Export to Single JSON File
        print("\n--- STAGE 3: Exporting to Single JSON ---")
        fetcher.export_to_single_json(args.output_json)
        
        print("\n[Done] High-performance automated collection workflow completed successfully!")
    except TokenExpiredError:
        print("\n\n[Stopped] Bearer token has expired or is invalid, and auto-refresh failed.")
        print("Please obtain a fresh Bearer token from your browser DevTools (Network tab -> index-khatian header) and run:")
        print("  python fetch_khatians.py --bearer-token \"<YOUR_NEW_TOKEN>\"")
        sys.exit(1)
    except KeyboardInterrupt:
        fetcher.stop_event.set()
        print("\n\n[Stopped] Scraping paused by user (Ctrl+C). All progress committed and saved to SQLite database.")
        sys.exit(0)

if __name__ == "__main__":
    main()

